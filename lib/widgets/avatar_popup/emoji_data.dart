import 'package:flutter/material.dart';

class EmojiList extends StatelessWidget {
  /// 列表
  final List<String> emojiList;

  final void Function(String) onSelect;
  const EmojiList({
    super.key,
    required this.emojiList, //
    required this.onSelect, //
  });

  @override
  Widget build(BuildContext context) {
    return Container(
      // margin: EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: Theme.of(context).colorScheme.surface,
        border: Border.all(color: Theme.of(context).colorScheme.surfaceContainer),
      ),
      child: GridView(
        gridDelegate: SliverGridDelegateWithFixedCrossAxisCount(crossAxisCount: 8, mainAxisSpacing: 2, crossAxisSpacing: 2),
        children:
            emojiList.map((e) {
              return Material(
                color: Theme.of(context).colorScheme.surfaceContainerLowest,
                child: InkWell(
                  onTap: () {
                    onSelect(e);
                  },
                  child: Center(
                    child: Text(
                      e, //
                      textAlign: TextAlign.center,
                      style: TextStyle(
                        fontSize: 16, //
                      ),
                    ),
                  ),
                ),
              );
            }).toList(),
      ),
    );
  }
}

